def is_observable(action):
    return action in OBSERVABLE


def validate(action):
    """Бросает ValueError на действие вне словаря — чтобы новый шаг атаки
    нельзя было тихо добавить в виде собственного «говорящего» действия."""
    if action not in ALL:
        raise ValueError(
            f"действие '{action}' вне нормализованного словаря. "
            "Добавь его в taxonomy.CORE/ADMIN и убедись, что обычная работа "
            "тоже его порождает — иначе имя действия станет меткой.")
    return action
