#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
PURPLE TEAM CONSOLE (контур «ЗАЩИТА») — порт 8788.

Полноценная SOC-консоль над общим event-store:
  • стрим-ингестор читает поток по курсору (переживает рестарт);
  • Detection Stack (detector.py: L0 правила + L1 UEBA + L2 ML + fusion)
    даёт алерты;
  • Correlator (correlator.py) склеивает алерты в ИНЦИДЕНТЫ с ATT&CK-цепочкой;
  • разделы: Обзор · Алерты · Инциденты · Дела · Очередь триажа ·
    ATT&CK Coverage · Детекты · Сущности · Профиль риска · Red Launcher ·
    Реплей прогона · Тренды · Диагностика.

«Мир» (8787) не трогаем; управление — через очередь команд в event-store
(кнопка «Запустить кампанию» ставит команду, мир её исполняет).

АНТИ-ЛИК: детектор и корреляция работают только на наблюдаемых полях
(run_defense.observed срезает разметку мира).

──────────────────────────────────────────────────────────────────────────
ЭТОТ ФАЙЛ — ТОЛЬКО ТОЧКА ВХОДА.

Сама консоль лежит в пакете console_app/: общее состояние и хелперы в
core.py, маршруты разложены по разделам (security, overview, incidents,
attack, metrics, system), стрим-ингестор и фоновые воркеры — в ingest.py.

Раньше здесь было 1841 строка: маршруты, ингестор, триаж, сборка HTML- и
PDF-отчётов и потоки в одном файле. Правка одного экрана требовала держать
в голове весь модуль — а дефекты, которые проект уже ловил на себе
(«половина панели навсегда осталась прочерками», «счётчик противоречит
содержимому панели»), рождаются ровно из этого.

Заодно исправлено: строка `import os.path as _os_path` стояла ВЫШЕ shebang
и docstring, из-за чего литерал переставал быть документацией модуля и
console.__doc__ был None.
"""
import config
from console_app import create_app

#: Приложение на уровне модуля — на него рассчитывают tests/test_routes.py и
#: инструменты, импортирующие `console.app`.
app = create_app()


def main():
    port = getattr(config, "PURPLE_WEB_PORT", 8788)
    # Адрес — из конфигурации, а не литералом: внутри контейнера привязка к
    # петле делает опубликованные порты недостижимыми, и документированный
    # `docker compose up` не работал вовсе.
    host = getattr(config, "WEB_HOST", "127.0.0.1")
    shown = "127.0.0.1" if host in ("0.0.0.0", "::") else host
    print("========================================================")
    print("  PURPLE TEAM CONSOLE (защита)")
    print(f"  Открой: http://{shown}:{port}")
    print(f"  Логин: {config.WEB_ADMIN_USER}")
    # Пароль печатаем ТОЛЬКО когда сгенерировали сами. Раньше он выводился
    # всегда, включая заданный оператором, — и уезжал в журнал контейнера,
    # в systemd-journal и в скриншот терминала.
    if getattr(config, "_WEB_PASS_GENERATED", False):
        print(f"  ПАРОЛЬ (сгенерирован): {config.WEB_ADMIN_PASS}")
        print("  (задайте свой: переменная окружения SOC_ADMIN_PASS)")
    if host not in ("127.0.0.1", "localhost", "::1"):
        print(f"  ВНИМАНИЕ: слушаем {host} — консоль доступна из сети.")
    print("========================================================")
    app.run(host=host, port=port, threaded=True, debug=False,
            use_reloader=False)


if __name__ == "__main__":
    main()
